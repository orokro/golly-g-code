/**
 * @file make-serpentine.mjs
 * @description Generates a chirped serpentine SVG for stressing the offsetter.
 *
 * Usage: node lab/make-serpentine.mjs [out.svg]
 *
 * Both the wavelength and the amplitude sweep along the path, so the radius of
 * curvature at the peaks falls from comfortably larger than a typical offset
 * distance to very much smaller than it. That matters because a normal offset
 * behaves completely differently either side of that threshold: while the radius
 * exceeds the offset the result is well behaved, and once it drops below, the
 * inside of every bend folds over itself. One picture covers both regimes and
 * the transition between them, which is exactly what makes a fold filter easy or
 * hard to judge.
 *
 * Emitted as a <polyline> in explicit millimetres: polyline is the primitive
 * jscut rejects outright, and real units mean the file is not open to any
 * resolution guesswork.
 */

import fs from 'node:fs';

const WIDTH = 300;
const HEIGHT = 120;
const CENTRE_Y = HEIGHT / 2;

/** Wavelength at the left and right ends, millimetres. */
const LAMBDA_START = 90;
const LAMBDA_END = 7;

/** Amplitude at the left and right ends, millimetres. */
const AMPLITUDE_START = 14;
const AMPLITUDE_END = 8;

/** Sampling step along x, millimetres. */
const STEP = 0.25;

const lerp = (a, b, t) => a + ((b - a) * t);

const points = [];
let phase = 0;

for (let x = 0; x <= WIDTH; x += STEP) {

	const t = x / WIDTH;
	const lambda = lerp(LAMBDA_START, LAMBDA_END, t);
	const amplitude = lerp(AMPLITUDE_START, AMPLITUDE_END, t);

	// integrate the local frequency, so the wave stays continuous as it chirps
	phase += (2 * Math.PI * STEP) / lambda;

	points.push([x, CENTRE_Y + (amplitude * Math.sin(phase))]);
}

/**
 * Radius of curvature at the peak of a sine wave.
 *
 * @param {Number} lambda - wavelength in millimetres
 * @param {Number} amplitude - amplitude in millimetres
 * @returns {Number} the radius of curvature at the crest, millimetres
 */
const peakRadius = (lambda, amplitude) => (lambda * lambda) / (4 * Math.PI * Math.PI * amplitude);

const out = process.argv[2] ?? 'serpentine.svg';

fs.writeFileSync(out, `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by lab/make-serpentine.mjs -->
<svg xmlns="http://www.w3.org/2000/svg"
     width="${WIDTH}mm" height="${HEIGHT}mm" viewBox="0 0 ${WIDTH} ${HEIGHT}">
  <polyline fill="none" stroke="#000" stroke-width="0.4"
            points="${points.map(([x, y]) => `${x.toFixed(3)},${y.toFixed(3)}`).join(' ')}"/>
</svg>
`);

console.log(`${out}: ${points.length} points, ${WIDTH} x ${HEIGHT} mm`);
console.log(`  peak radius of curvature: ${peakRadius(LAMBDA_START, AMPLITUDE_START).toFixed(2)} mm at the left`
	+ `, ${peakRadius(LAMBDA_END, AMPLITUDE_END).toFixed(3)} mm at the right`);
console.log('  a 1.5 mm offset therefore folds somewhere in the middle, which is the point');
